async function seed(){
  const casesRef = db.collection('cases');
  const snap = await casesRef.orderBy('id','desc').limit(1).get();
  let nextId = snap.empty ? 1 : (snap.docs[0].data().id + 1);

  const batch = db.batch();
  NEW_CASES.forEach(c=>{
    const id = nextId++;
    const docRef = casesRef.doc(String(id));
    batch.set(docRef, Object.assign({ id }, c));
  });
  await batch.commit();
  console.log(`تمت إضافة ${NEW_CASES.length} حالة جديدة بنجاح، بدءًا من id = ${nextId - NEW_CASES.length}.`);
}

seed().catch(e=>{ console.error('حدث خطأ أثناء الإضافة:', e); process.exit(1); });
